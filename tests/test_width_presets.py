"""Width presets and the ModelConfig positivity checks (milestone 9 design 3.1; no TensorFlow).

Runs in bgr_preproc38 (no TF) as well as tf_gpu; `test_no_tensorflow` asserts that neither
`models.width_presets` nor `models.config` imports TF.
"""
import sys
import unittest

from models import width_presets as W
from models.config import ModelConfig


class TestPresets(unittest.TestCase):
    def test_table(self):
        self.assertEqual(list(W.PRESETS), ["default", "u075", "u050", "u0375", "f0d1", "fr50", "fr25"])
        self.assertEqual(W.PRESETS["default"], {"filters": (32, 64, 128, 192, 256, 384),
                                                "decoder_widths": (128, 96, 64, 32, 16)})
        self.assertEqual(W.PRESETS["f0d1"], {"filters": (16, 64, 128, 192, 256, 384),
                                             "decoder_widths": (128, 96, 64, 32, 8)})
        self.assertEqual(W.PRESETS["fr50"], {"filters": (16, 32, 128, 192, 256, 384),
                                             "decoder_widths": (128, 96, 64, 16, 8)})
        self.assertEqual(W.PRESETS["fr25"], {"filters": (8, 16, 128, 192, 256, 384),
                                             "decoder_widths": (128, 96, 64, 8, 8)})
        for name, m in W.UNIFORM_FACTORS.items():
            self.assertEqual(W.PRESETS[name], W.uniform(m), name)      # table generated by uniform()
        self.assertEqual(W.uniform(1.0), W.PRESETS["default"])
        for name in W.PRESETS:
            ModelConfig(**W.preset_kwargs(name))                         # every preset validates

    def test_uniform_rounding(self):
        self.assertEqual(W.uniform_width(16, 0.375), 8)      # 6 -> floor(0.75 + 0.5) = 1 -> 8
        self.assertEqual(W.uniform_width(32, 0.375), 16)     # 12 -> floor(1.5 + 0.5) = 2 -> 16
        self.assertEqual(W.uniform_width(96, 0.375), 40)     # 36 -> floor(4.5 + 0.5) = 5 -> 40
        self.assertEqual(W.uniform_width(16, 0.25), 8)       # max(8, ...)
        self.assertEqual(W.uniform_width(384, 0.75), 288)
        for name in W.UNIFORM_FACTORS:
            p = W.PRESETS[name]
            self.assertTrue(all(w % 8 == 0 and w >= 8 for w in p["filters"] + p["decoder_widths"]), name)

    def test_unknown_name(self):
        for fn in (W.preset_kwargs, W.preset_args):
            with self.assertRaises(ValueError) as cm:
                fn("u060")
            msg = str(cm.exception)
            self.assertIn("u060", msg)
            for name in W.PRESETS:
                self.assertIn(name, msg)

    def test_preset_args_and_kwargs(self):
        self.assertEqual(W.preset_args("f0d1"), ["--filters", "16,64,128,192,256,384",
                                                 "--decoder-widths", "128,96,64,32,8"])
        kw = W.preset_kwargs("u050")
        self.assertEqual(kw, {"filters": (16, 32, 64, 96, 128, 192), "decoder_widths": (64, 48, 32, 16, 8)})
        kw["filters"] = (1,)
        self.assertEqual(W.PRESETS["u050"]["filters"], (16, 32, 64, 96, 128, 192))   # a copy
        # The explicit 'default' preset builds ModelConfig()'s widths but is not dict-equal.
        cfg = ModelConfig(**W.preset_kwargs("default"))
        self.assertEqual(cfg.resolved_decoder_widths(), ModelConfig().resolved_decoder_widths())
        self.assertNotEqual(cfg.to_dict(), ModelConfig().to_dict())

    def test_count_params_parts(self):
        c = W.count_params(dict(deform_decoder=True, **W.preset_kwargs("default")))
        self.assertEqual(list(c), ["encoder", "linear_decoder", "deform_decoder", "total"])
        self.assertEqual(c["total"], c["encoder"] + c["linear_decoder"] + c["deform_decoder"])
        print("\n[presets] trainable parameters (M, deform decoder on):", file=sys.stderr)
        for name in W.PRESETS:
            p = W.count_params(name, deform_decoder=True)
            print("  %-6s total %.2f  encoder %.2f  linear %.2f  deform %.2f" % (
                name, p["total"] / 1e6, p["encoder"] / 1e6, p["linear_decoder"] / 1e6,
                p["deform_decoder"] / 1e6), file=sys.stderr)
        self.assertAlmostEqual(W.count_params("default", deform_decoder=True)["total"] / 1e6, 29.63, delta=0.01)
        self.assertAlmostEqual(W.count_params("f0d1", deform_decoder=True)["total"] / 1e6, 29.54, delta=0.01)
        self.assertEqual(W.count_params(ModelConfig())["deform_decoder"], 0)      # flag off
        self.assertEqual(W.count_params(ModelConfig(), deform_decoder=True)["total"],
                         W.count_params("default", deform_decoder=True)["total"])

    def test_no_tensorflow(self):
        # Under the full suite other test modules import TF first, so check the imports of the
        # two modules themselves (bgr_preproc38 has no TF at all).
        import ast
        import inspect
        for mod in (W, sys.modules["models.config"]):
            tree = ast.parse(inspect.getsource(mod))
            names = [a.name for n in ast.walk(tree) if isinstance(n, ast.Import) for a in n.names]
            names += [n.module for n in ast.walk(tree) if isinstance(n, ast.ImportFrom) and n.module]
            self.assertFalse(any(x.split(".")[0] == "tensorflow" for x in names), mod.__name__)


class TestModelConfigPositivity(unittest.TestCase):
    def test_errors_name_the_field(self):
        cases = [("filters", dict(filters=(32, 64, 0, 192, 256, 384))),
                 ("filters", dict(filters=(32, 64, 128, 192, 256, -1))),
                 ("reductions", dict(reductions=(192, 0))),
                 ("dense", dict(dense=(2048, -512)))]
        for field, kw in cases:
            with self.assertRaises(ValueError) as cm:
                ModelConfig(**kw)
            self.assertIn(field, str(cm.exception), kw)

    def test_existing_configs_pass(self):
        ModelConfig()
        ModelConfig(filters=(16, 32, 32, 48, 64, 96), reductions=(64, 48, 24, 24), dense=(512, 256))
        ModelConfig(filters=(8, 16, 16, 16, 16, 16), reductions=(16, 8), dense=(64, 32),
                    decoder_widths=(8, 8, 8, 8, 8))
        d = ModelConfig().to_dict()                  # today's config.json format restores
        self.assertEqual(ModelConfig.from_dict(d), ModelConfig())


if __name__ == "__main__":
    unittest.main()
